import 'dart:io';

import 'package:dart_style/dart_style.dart';
import 'package:recase/recase.dart';
import 'package:xml/xml.dart';

import 'xml_to_map.dart';

void main(List<String> args) {
  final fontsConfigFile = File('./fonts/Warframe-Symbols.ttx');

  if (!fontsConfigFile.existsSync()) {
    // ignore: avoid_print Don't worry about it
    print('config files not found');
    exit(0);
  }

  FontGenerator(fontFile: fontsConfigFile).createIconDataFile();
}

class FontGenerator {
  FontGenerator({required this.fontFile}) {
    icons = _readIcons();
  }

  final File fontFile;

  late final Map<String, String> icons;

  /// read the icon data from the [fontFile]
  Map<String, String> _readIcons() {
    final content = fontFile.readAsStringSync();
    final document = XmlDocument.parse(content);

    final icons = xmlToIcons(document).map((key, value) {
      final name = ReCase(key).camelCase;
      return MapEntry<String, String>(name, value);
    });

    return icons;
  }

  /// creates the icon_data.g.dart containing links to the font file
  void createIconDataFile() {
    final formatter = DartFormatter(languageVersion: DartFormatter.latestLanguageVersion, pageWidth: 120);
    final buffer = StringBuffer()
      ..writeln('// THIS FILE IS AUTOMATICALLY GENERATED!')
      ..writeln("import 'package:flutter/widgets.dart';")
      ..writeln("const _fontFamily = 'Warframe-Symbols';")
      ..writeln("const _fontPackage = 'warframe_icons';")
      ..writeln('/// [WarframeIcons] offers icons from multiple Warframe sources converted to an icon font')
      ..writeln('class WarframeIcons {');

    icons.forEach((iconName, iconUnicode) {
      buffer
        ..writeln('/// Warframe icons $iconName [IconData] with Unicode $iconUnicode')
        ..writeln(
          'static const IconData $iconName = IconData($iconUnicode, fontFamily: _fontFamily, fontPackage: _fontPackage);',
        );
    });

    buffer.writeln('}');

    final generatedFile = formatter.format(buffer.toString());
    File('./lib/src/warframe_symbols.g.dart').writeAsStringSync(generatedFile);
  }
}
